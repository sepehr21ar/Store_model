CREATE OR REPLACE FUNCTION validate_and_apply_sale()
RETURNS TRIGGER AS $$
DECLARE
    product_is_active BOOLEAN;
    available_quantity INTEGER;
BEGIN
    SELECT availability
    INTO product_is_active
    FROM products
    WHERE product_id = NEW.product_id;

    IF product_is_active IS NULL THEN
        RAISE EXCEPTION 'Product % was not found.', NEW.product_id;
    END IF;

    IF product_is_active IS NOT TRUE THEN
        RAISE EXCEPTION 'Product % is inactive and cannot be sold.', NEW.product_id;
    END IF;

    SELECT quantity
    INTO available_quantity
    FROM storage
    WHERE product_id = NEW.product_id
    FOR UPDATE;

    IF COALESCE(available_quantity, 0) < NEW.quantity THEN
        RAISE EXCEPTION 'Insufficient stock for product %. Requested: %, Available: %.',
            NEW.product_id, NEW.quantity, COALESCE(available_quantity, 0);
    END IF;

    UPDATE storage
    SET quantity = quantity - NEW.quantity
    WHERE product_id = NEW.product_id;

    DELETE FROM storage
    WHERE product_id = NEW.product_id
      AND quantity = 0;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_before_store_sale ON store_sales;
CREATE TRIGGER trg_before_store_sale
BEFORE INSERT ON store_sales
FOR EACH ROW
EXECUTE FUNCTION validate_and_apply_sale();

DROP TRIGGER IF EXISTS trg_before_online_sale ON online_sales;
CREATE TRIGGER trg_before_online_sale
BEFORE INSERT ON online_sales
FOR EACH ROW
EXECUTE FUNCTION validate_and_apply_sale();

